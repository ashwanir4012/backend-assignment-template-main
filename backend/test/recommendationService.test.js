const test = require("node:test");
const assert = require("node:assert/strict");

const Program = require("../src/models/Program");
const Student = require("../src/models/Student");
const { buildProgramRecommendations } = require("../src/services/recommendationService");

test("recommendations are generated by an aggregation pipeline and limited to five", async () => {
  const originalFindById = Student.findById;
  const originalAggregate = Program.aggregate;
  let capturedPipeline;
  Student.findById = () => ({ lean: async () => ({
    _id: "student-1", fullName: "Aarav", targetCountries: ["Canada"],
    interestedFields: ["Computer Science"], preferredIntake: "September",
    maxBudgetUsd: 25000, englishTest: { score: 7 },
  }) });
  Program.aggregate = async (pipeline) => {
    capturedPipeline = pipeline;
    return [{ title: "Master of Applied Computing", matchScore: 100, reasons: ["Within budget"] }];
  };

  try {
    const result = await buildProgramRecommendations("student-1");
    assert.equal(result.meta.implementation, "mongodb-aggregation");
    assert.equal(result.data.recommendations[0].matchScore, 100);
    assert.ok(capturedPipeline.some((stage) => stage.$addFields?.matchScore));
    assert.deepEqual(capturedPipeline.find((stage) => stage.$limit), { $limit: 5 });
  } finally {
    Student.findById = originalFindById;
    Program.aggregate = originalAggregate;
  }
});
